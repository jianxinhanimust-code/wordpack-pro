  await expect(preview.filter({ hasText: 'adapt' }).getByText('星辉异种', { exact: false })).toBeVisible()
  const motifs = await preview.evaluateAll(cards => cards.map(card => (card as HTMLElement).dataset.motif))
  expect(new Set(motifs).size).toBe(5)
  await expect.poll(() => preview.locator('canvas').evaluateAll(images => new Set(images.map(image =>
    (image as HTMLCanvasElement).toDataURL())).size)).toBe(5)
  const rows = await page.locator('.reveal-slot').evaluateAll(cards => new Set(cards.map(card => (card as HTMLElement).offsetTop)).size)
  expect(rows).toBe(isMobile ? 2 : 1)
  await expect(page.locator('.resonance-beam')).toBeVisible()
  await page.getByRole('button', { name: '跳过动画' }).click()
  const firstCard = page.getByRole('button', { name: '预览词卡 sustain' })
  if (isMobile) await firstCard.tap()
  else await firstCard.click()
  const viewer = page.getByRole('dialog', { name: '词卡预览' })
  await expect(viewer).toBeVisible()
  const turnCard = viewer.getByRole('button', { name: '翻看中文释义' })
